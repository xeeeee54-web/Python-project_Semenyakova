#Вариант 29. Дни недели пронумерованы следующим образом: 0 — воскресенье, 1— понедельник, 2 — вторник, ..., 6 — суббота. Дано целое число K, лежащее в диапазоне1-365. Определить номер дня недели для K-го дня года, если известно, что в этом году 1января было понедельником
while True: #цикл будет повторятся пока мы не введем правилное число
    try: #пробуем выполнить код без ошибок
        K = int(input("введите номер дня года от 1 до 365 :"))
        #проверяем , входит ли K в  диапозоне от 1 до 365
        if K < 1 or K > 365:
            print("ошибка! введите ЧИСЛО от 1 до 365")
            continue #возвращает в начало цикла
        #вычисляем номер дня недели
        day = K % 7
        #если остаток равень 0 то воскресение 1 это понеделинк и т.д
        print("номер дня недели", day)
        break #Если цикл правильный то завершаем цикл

    except ValueError:
        print("ошибка!введите ЦЕЛОЕ число")